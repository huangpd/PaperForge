"""Run the whole test suite and write docs/test_report.md from the real JUnit results (nothing is hand-typed).
Needs the services up (`make up`).  uv run python scripts/gen_test_report.py"""
import platform
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
XML = ROOT / "data" / "reports" / "junit.xml"

# requirement §17 -> test functions that exercise it
REQUIRED = [
    ("1", "Duplicate ingestion of the same DOI", ["test_duplicate_same_doi_no_new_entity_or_version", "test_duplicate_ingest_does_not_duplicate"]),
    ("2", "Metadata of the same DOI changes", ["test_metadata_change_creates_version_and_keeps_history", "test_changed_and_late_records"]),
    ("3", "Older version arrives after the newer one", ["test_late_older_version_is_history_only", "test_out_of_order_arrival_converges_to_same_state", "test_versions_history_with_late_and_newer_versions"]),
    ("4", "Ingestion interrupted, then resumed", ["test_ingest_interrupted_and_resumed", "test_orphan_file_from_crash_is_overwritten_not_duplicated"]),
    ("5", "Kafka consumer interrupted, then resumed", ["test_consumer_interrupted_then_resumes_from_committed_offset", "test_persistent_db_outage_crashes_worker_without_committing"]),
    ("6", "Data written but offset not yet committed", ["test_write_succeeded_but_offset_not_committed"]),
    ("7", "Raw JSON gains or lacks fields", ["test_added_and_missing_fields_do_not_break", "test_missing_optional_fields_do_not_drop_paper", "test_garbage_numbers_are_nulled_not_crashing"]),
    ("8", "Data quality validation fails", ["test_error_rule_quarantines_only_bad_records", "test_quality_run_clean_then_detects_violations", "test_poison_events_go_to_dlq_and_can_be_replayed", "test_dbt_data_tests_catch_broken_data"]),
    ("9", "Historical replay", ["test_historical_replay_rebuilds_same_state_and_is_idempotent", "test_quarantine_replay_after_fix", "test_batch_mode_from_raw_files_reconciles_with_ods"]),
    ("10", "Batch / streaming consistency", ["test_batch_and_streaming_produce_identical_results", "test_batch_vs_single_event_processing_same_result", "test_refresh_inside_same_chunk_equals_separate_chunks"]),
    ("11", "dbt incremental vs full refresh", ["test_dbt_incremental_equals_full_refresh"]),
    ("12", "Raw vs standardized reconciliation", ["test_batch_mode_from_raw_files_reconciles_with_ods", "test_reconciliation_endpoint_uses_duckdb_over_parquet", "test_pipeline_produced_consistent_layers"]),
    ("+", "External identifier change on isolated test data; real warehouse untouched", ["test_external_identifier_change_is_representable_and_isolated"]),
]


def main() -> int:
    XML.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([sys.executable, "-m", "pytest", "tests", "-q", f"--junitxml={XML}", "-p", "no:cacheprovider"], cwd=ROOT, capture_output=True, text=True)
    tree = ET.parse(XML).getroot()
    suite = tree if tree.tag == "testsuite" else tree.find("testsuite")
    cases = []
    for tc in suite.iter("testcase"):
        status = "failed" if tc.find("failure") is not None or tc.find("error") is not None else "skipped" if tc.find("skipped") is not None else "passed"
        cases.append((tc.get("classname").replace(".", "/") + ".py", tc.get("name"), status, float(tc.get("time", 0))))
    by_file = defaultdict(lambda: [0, 0, 0, 0.0])
    for f, _n, s, t in cases:
        row = by_file[f]
        row[0] += 1; row[1] += s == "passed"; row[2] += s == "failed"; row[3] += t
    status = {n: s for _f, n, s, _t in cases}
    total, passed = len(cases), sum(c[2] == "passed" for c in cases)
    layer = lambda f: f.split("/")[1]
    L = ["# Test report", "", f"Generated by `scripts/gen_test_report.py` on {datetime.now():%Y-%m-%d %H:%M} · Python {platform.python_version()} · {platform.system()} {platform.machine()}.",
         "Results come from `pytest --junitxml` (`data/reports/junit.xml`); integration and e2e tests use real PostgreSQL and Kafka but **isolated databases / topics / dbt targets**, never the real warehouse.", "",
         f"## Result: {passed}/{total} passed" + ("" if passed == total else f" — **{total - passed} not passing**"), "",
         "| layer | tests | passed | failed | time (s) |", "|---|---:|---:|---:|---:|"]
    for lay in ("unit", "integration", "e2e"):
        rows = [(f, v) for f, v in by_file.items() if layer(f) == lay]
        L.append(f"| {lay} | {sum(v[0] for _, v in rows)} | {sum(v[1] for _, v in rows)} | {sum(v[2] for _, v in rows)} | {sum(v[3] for _, v in rows):.1f} |")
    L += ["", "| file | tests | passed | failed | time (s) |", "|---|---:|---:|---:|---:|"]
    L += [f"| `{f}` | {v[0]} | {v[1]} | {v[2]} | {v[3]:.1f} |" for f, v in sorted(by_file.items())]
    L += ["", "## Required fault drills and tests (requirement §17)", "", "| # | scenario | covering tests | result |", "|---|---|---|---|"]
    for num, title, names in REQUIRED:
        res = [status.get(n, "MISSING") for n in names]
        ok = "all passed" if all(x == "passed" for x in res) else "; ".join(f"{n}: {x}" for n, x in zip(names, res) if x != "passed")
        L.append(f"| {num} | {title} | {'<br>'.join(f'`{n}`' for n in names)} | {ok} |")
    L += ["", "## Drills run against the real data (not part of pytest)", "",
          "- Kafka worker container killed with `SIGKILL` at lag ≈ 44,000, restarted: resumed from the committed offset, lag 0, DWD unchanged (101,000 papers / 101,000 versions) — `docs/stage4-report.md`.",
          "- Streaming rebuild of the whole DWD from Kafka (101,000 events): `dwd.paper` and the version timeline have the same MD5 as the batch-built result — `docs/stage4-report.md`.",
          "- Airflow `dags test` of all 4 DAGs inside the Airflow container, including a deliberate failure (3 attempts, DAG run failed) — `docs/stage5-report.md`.",
          "- Browser checks of the console (`frontend/ui-check.mjs`): search, detail drawer with raw-vs-standardized and versions, lineage selection, pipeline run expansion, catalog deep link, quality filters; no console errors, no failed API calls.",
          "", "## Failures", ""]
    fails = [c for c in cases if c[2] == "failed"]
    L += [f"- `{f}::{n}`" for f, n, _s, _t in fails] or ["None."]
    if r.returncode:
        L += ["", "```", (r.stdout + r.stderr)[-3000:], "```"]
    (ROOT / "docs" / "test_report.md").write_text("\n".join(L) + "\n")
    print(f"{passed}/{total} passed; wrote docs/test_report.md")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
